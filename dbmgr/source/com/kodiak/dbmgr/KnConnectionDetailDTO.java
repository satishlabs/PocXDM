package com.kodiak.dbmgr;

class KnConnectionDetailDTO {

	private String userName;
	private String password;
	private String pttserverId;
	private String dsn;
	private String ipAddress;
	private int port;

	public String getUserName() {
		return userName;
	}

	public void setUserName(String userName) {
		this.userName = userName;
	}

	public String getPassword() {
		return password;
	}

	public void setPassword(String password) {
		this.password = password;
	}

	public String getPttserverId() {
		return pttserverId;
	}

	public void setPttserverId(String pttserverId) {
		this.pttserverId = pttserverId;
	}

	public String getDsn() {
		return dsn;
	}

	public void setDsn(String dsn) {
		this.dsn = dsn;
	}

	public String getIpAddress() {
		return ipAddress;
	}

	public void setIpAddress(String ipAddress) {
		this.ipAddress = ipAddress;
	}

	public int getPort() {
		return port;
	}

	public void setPort(int port) {
		this.port = port;
	}

	@Override
	public String toString() {
		StringBuilder builder = new StringBuilder();
		builder.append("KnConnectionDetailDTO [userName=").append(userName).append(", pttserverId=")
				.append(pttserverId).append(", dsn=").append(dsn).append(", ipAddress=").append(ipAddress).append(", port=").append(port).append("]");
		return builder.toString();
	}
}
