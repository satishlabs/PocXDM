import com.kodiak.frameworks.jobscheduler.resources.KnJobSchedulerException;
import com.kodiak.logger.KnLogger;

import com.kodiak.xdms.mediator.helper.KnXDMCommonMediator;
import com.kodiak.xdms.mediator.resources.KnInconsistenUPMDataDTO;
import com.kodiak.xdms.mediator.resources.jobs.asyncframework.KnUPMJobScheduler;
import com.kodiak.xdms.server.common.business.KnBOException;
import com.kodiak.xdms.server.common.business.helper.KnGenInfoUtil;
import com.kodiak.xdms.server.common.dto.common.KnEmergencyInfoDTO;
import com.kodiak.xdms.server.common.resources.KnConstants;
import com.kodiak.xdms.server.corpmgmt.business.helper.KnCorpCommonInfoUtil;
import com.kodiak.xdms.server.corpmgmt.dao.persister.db.KnCorpXdmDAO;
import com.kodiak.xdms.server.corpmgmt.dto.common.*;

import java.util.*;
import java.util.stream.Collectors;

public class KnInconsistentUPMDataAuditThread extends KnAbstractJob implements Runnable {
    private static final KnLogger knLogger = KnLogger.getLogger(KnInconsistentUPMDataAuditThread.class);
    KnInconsistenUPMDataDTO knInconsistenUPMDataDTO = new KnInconsistenUPMDataDTO();
    private KnXDMCommonMediator commonMediator = KnXDMCommonMediator.getInstance();
    private KnUPMJobScheduler upmJobScheduler = KnUPMJobScheduler.getInstance();

    @Override
    public boolean executeTask() throws KnJobSchedulerException {
        String methodName = "executeTask()";
        knLogger.info(methodName, "Getting into Inconsistent UPM Data Audit");
        KnGenInfoUtil knGenInfoUtil = KnGenInfoUtil.getInstance();
        KnCorpUserProfileDTO userProfileDetails = new KnCorpUserProfileDTO();
        KnEmergencyInfoDTO emergencyInfoDTOFromTT = new KnEmergencyInfoDTO();
        KnSubsDestEmergencyAttributes destEmergencyAttributes = new KnSubsDestEmergencyAttributes();
        String xdmPttServerId;
        try {
            xdmPttServerId = KnGenInfoUtil.getInstance().retrieveLocalXDMPttServerId();
        } catch (KnBOException e) {
            throw new RuntimeException(e);
        }
        KnCorpXdmDAO xdmDAO = new KnCorpXdmDAO(xdmPttServerId);
        try {
            List<String> allCorpIds = knGenInfoUtil.getAllCorpIds();
            Map<String, KnCorpUserProfileDTO> userProfileDetailsMap = new HashMap<>();
            for (String corpId : allCorpIds) {
                knLogger.debug("corpId::", corpId);
                int allSubsCountInCorp = knGenInfoUtil.getAllSubscribersCount(Integer.parseInt(corpId));
                knLogger.debug(methodName, "All Subscribers Count in Corp- ", allSubsCountInCorp);
                int tempRecord = 0, maxRecordFetch = 10;
                while (tempRecord < allSubsCountInCorp) {
                    Map<String, String> profileMDNsWithMCID = new HashMap<>();
                    profileMDNsWithMCID = knGenInfoUtil.profileMdnswithMCID(Integer.parseInt(corpId), tempRecord, tempRecord + maxRecordFetch);
                    tempRecord += maxRecordFetch;
                    List<String> profileMDNswithNoBaseMDN = knGenInfoUtil.profileMdnswithNoBaseMDN(profileMDNsWithMCID);
                    knInconsistenUPMDataDTO.setProfileMdnswithNoBaseMDN(profileMDNswithNoBaseMDN);
                    knLogger.debug(methodName, "Profile MDNs with No Base MDN - ", profileMDNswithNoBaseMDN.size());
                }
                List<KnCorpUserProfileDTO> listOfDistinctUserProfiles = xdmDAO.getAllDistinctUPMByCorp(corpId);
                knLogger.debug("DistinctUPMSize::", listOfDistinctUserProfiles.size());
                for (KnCorpUserProfileDTO corpUserProfileDTO : listOfDistinctUserProfiles) {
                    List<String> groupIdsFromCBS = new ArrayList<>();
                    String userProfileId = corpUserProfileDTO.get_id();
                    userProfileDetails = xdmDAO.getUserProfile(userProfileId);
                    List<String> profileMdnsInUPM = knGenInfoUtil.getProfileMdnsForUPMId(userProfileId).get(userProfileId);
                    userProfileDetailsMap.put(userProfileId, userProfileDetails);
                    for (KnCorpGroupListInfoDTO group : userProfileDetails.getGroupList()) {
                        groupIdsFromCBS.add(String.valueOf(group.getGroupID()));
                    }
                    Map<String, List<String>> groupIdsProfileMdnPartOf = new HashMap<>();
                    for (String profileMdnItr : profileMdnsInUPM) {
                        groupIdsProfileMdnPartOf = knGenInfoUtil.getInconsistenGroupId(profileMdnItr, groupIdsFromCBS);
                        Map<String, List<String>> finalGroupIdsProfileMdnPartOf = groupIdsProfileMdnPartOf;
                        List<String> addInconsistentGroupIds = groupIdsFromCBS.stream().filter(id -> !finalGroupIdsProfileMdnPartOf.values().stream().flatMap(List::stream).collect(Collectors.toList()).contains(id)).collect(Collectors.toList());
                        knInconsistenUPMDataDTO.setAddGroupIds(addInconsistentGroupIds);
                        List<String> groupIdsForProfileMdn = knGenInfoUtil.getGroupIdsForProfileMdn(profileMdnItr);
                        List<String> removeInconsistentGroupIds = groupIdsForProfileMdn.stream().filter(id -> !groupIdsFromCBS.contains(id)).collect(Collectors.toList());
                        knInconsistenUPMDataDTO.setRemoveGroupIds(removeInconsistentGroupIds);
                        String featureBSForProfileMdnFromTT = null;
                        if (userProfileDetails.getContactListID() != null) {
                            Integer contactListIDFromCBS = userProfileDetails.getContactListID();
                            List<String> inconsistantProfileMdns = new ArrayList<>();
                            Map<String, String> featureBSForUPMIdFromCBS = new HashMap<>();
                            Map<String, List<String>> contactMdnsFromCBSublistMap = knGenInfoUtil.getSublistIdContactMdnMap(String.valueOf(contactListIDFromCBS));
                            List<String> contactListFromSublistCBS = new ArrayList<>(contactMdnsFromCBSublistMap.values()).get(0);
                            featureBSForUPMIdFromCBS.put(userProfileId, userProfileDetails.getFeatureBS());
                            try {
                                Map<String, List<String>> contactsAssignedToProfileMdnFromTT = knGenInfoUtil.getContactMdnByProfileMdn(profileMdnItr);
                                List<String> contactListForProfileMdnFromTT = new ArrayList<>(contactsAssignedToProfileMdnFromTT.values()).get(0);
                                List<String> addContacts = contactListFromSublistCBS.stream()
                                        .filter(contact -> !contactListForProfileMdnFromTT.contains(contact))
                                        .collect(Collectors.toList());
                                knInconsistenUPMDataDTO.setAddContacts(addContacts);
                                List<String> removeContacts = contactListForProfileMdnFromTT.stream()
                                        .filter(contact -> !contactListFromSublistCBS.contains(contact))
                                        .collect(Collectors.toList());
                                knInconsistenUPMDataDTO.setRemoveContacts(removeContacts);
                                featureBSForProfileMdnFromTT = knGenInfoUtil.getFeatureBSForProfileMdnFromTT(profileMdnItr);
                                if (!featureBSForUPMIdFromCBS.get(userProfileId).equals(featureBSForProfileMdnFromTT)) {
                                    knInconsistenUPMDataDTO.setUpdateUPMFS(featureBSForUPMIdFromCBS.get(userProfileId));
                                }
                            } catch (KnBOException | KnDAOException e) {
                                throw new RuntimeException(e);
                            }
                        }
                        KnSubsEmergencyConfigDTO emergencyConfigFromCBS = userProfileDetails.getEmergencyConfig();
                        emergencyInfoDTOFromTT = knGenInfoUtil.getEmergencyInfoForProfileMdn(profileMdnItr);
                        Set<KnDestinationAttributeDTO> destAttributes = emergencyConfigFromCBS.getDestAttributes();
                        List<String> destURIs = new ArrayList<>();
                        List<Integer> destCats = new ArrayList<>();
                        for (KnDestinationAttributeDTO destAttribute : destAttributes) {
                            destURIs.add(destAttribute.getDestURI());
                            destCats.add(destAttribute.getDestCat());
                        }
                        if (emergencyConfigFromCBS.getDestType() != null && emergencyInfoDTOFromTT.getDestType() == null || !destURIs.isEmpty() && emergencyInfoDTOFromTT.getDestination().isEmpty() || !destCats.isEmpty() && emergencyInfoDTOFromTT.getDestPriority() == null) {
                            destEmergencyAttributes.setMdn(profileMdnItr);
                            destEmergencyAttributes.setEmergDestTypeMgmt(emergencyConfigFromCBS.getDestType());
                            knInconsistenUPMDataDTO.setAddDestEmergencyAttributes(destEmergencyAttributes);
                        }
                        if (emergencyConfigFromCBS.getDestType() == null && emergencyInfoDTOFromTT.getDestType() != null || destURIs.isEmpty() && !emergencyInfoDTOFromTT.getDestination().isEmpty() || destCats.isEmpty() && emergencyInfoDTOFromTT.getDestPriority() != null) {
                            destEmergencyAttributes.setMdn(profileMdnItr);
                            destEmergencyAttributes.setEmergDestTypeMgmt(emergencyConfigFromCBS.getDestType());
                            knInconsistenUPMDataDTO.setRemoveDestEmergencyAttributes(destEmergencyAttributes);
                        }
                        String inConsistentUpmJsonString = KnCorpCommonInfoUtil.ObjToJson(knInconsistenUPMDataDTO);
                        KnAsyncJobDTO knAsyncJobDTO = commonMediator.createJobNotifyDTO(corpId, KnCorpCommonInfoUtil.getUUID()
                                , userProfileId, KnConstants.UPM_OPERATION_TYPE.INCONSISTENT_DATA_UPM.Value(), profileMdnItr,
                                KnConstants.UPM_RESOURCE_TYPE.PROFILEMDN.Value(), inConsistentUpmJsonString, KnConstants.UPM_JOB_STATUS.NEW.Value(), null);
                        upmJobScheduler.addJob(knAsyncJobDTO);
                    }
                }
            }
        } catch (KnBOException | KnDAOException e) {
            knLogger.debug(methodName, "Exception Happened::", e.getMessage());
            throw new RuntimeException(e);
        } catch (Throwable e) {
            knLogger.debug(methodName, "Exception Happened::", e.getMessage());
        }

        return false;
    }

    @Override
    public void run() {
        try {
            executeTask();
        } catch (KnJobSchedulerException e) {
            knLogger.error("Error in executing task", e);
        }
    }
}
