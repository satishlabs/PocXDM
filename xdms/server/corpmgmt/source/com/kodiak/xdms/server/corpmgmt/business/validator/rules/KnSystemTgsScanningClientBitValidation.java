package com.kodiak.xdms.server.corpmgmt.business.validator.rules;


import com.kodiak.logger.KnLogger;
import com.kodiak.xdms.server.common.dto.intf.IPersistenceDTO;
import com.kodiak.xdms.server.common.framework.validator.KnValidationException;
import com.kodiak.xdms.server.common.framework.validator.KnValidatorRule;
import com.kodiak.xdms.server.corpmgmt.business.validator.KnCorpBOValidationException;
import com.kodiak.xdms.server.corpmgmt.dto.persistdat.KnCorpTGSPersistDTO;
import com.kodiak.xdms.server.corpmgmt.resources.KnErrorCodes;

public class KnSystemTgsScanningClientBitValidation extends KnValidatorRule {
    private static final KnLogger knLogger = KnLogger.getLogger(KnSystemTgsScanningClientBitValidation.class);

    public void validate() throws KnValidationException {
        final String methodName = "validate()";
        knLogger.debug(methodName, "ENTRY Point");
        IPersistenceDTO persistDTO = getDTO();
        if (persistDTO instanceof KnCorpTGSPersistDTO) {
            KnCorpTGSPersistDTO tgsPersistDTO = (KnCorpTGSPersistDTO) persistDTO;
            boolean isSysTgsScanningEnabled = tgsPersistDTO.isSystemTgscanningClientBitEanble();
            if(!isSysTgsScanningEnabled){
                throw new KnCorpBOValidationException(KnErrorCodes.Validator.TGS_CLIENT_SYSTEM_CONFIG_DISABLED,
                        "System wide TGS scanning client feature  disabled", getEntityId(), getOperationType(), getRuleId(),
                        "Business validation","");
            }

        } else{
            knLogger.error("validate", "Unexpected DTO passed - ", persistDTO.getClass(),
                    ", Expected Dto - KnCorpTGSPersistDTO ");
            throw new KnCorpBOValidationException(KnErrorCodes.Validator.INTERNAL_ERROR,
                    "Unexpected instance of persistence DTO passed - " + persistDTO.getClass(),
                    getEntityId(), getOperationType(), getRuleId(), "DataType", "");
        }
        knLogger.debug( methodName, "Validation Completed Successfully");
    }
}
